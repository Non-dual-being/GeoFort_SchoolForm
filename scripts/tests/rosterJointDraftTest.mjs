import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
const require=createRequire(import.meta.url), ts=require('typescript');
const source=fs.readFileSync(new URL('../../resources/js/admin/composables/useJointRosterDraft.ts',import.meta.url),'utf8');
let js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
js=js.replace(/from ['"]vue['"]/g,`from '${pathToFileURL(require.resolve('vue/dist/vue.runtime.esm-bundler.js')).href}'`);
const {useJointRosterDraft}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const base=[{id:1,sessions:[{id:11,start:'10:15',end:'11:00',cook:0,groups:[{id:101,kind:'staff',staffIds:[1]}]}]},{id:2,sessions:[{id:22,start:'11:00',end:'11:20',cook:0,groups:[{id:202,kind:'staff',staffIds:[2]}]}]}];
const initial=JSON.stringify(base);const draft=useJointRosterDraft(base,true,null,[1,2]);
assert.equal(draft.dirty.value,false);
draft.edit(d=>{d[0].sessions[0].groups[0].staffIds=[2];d[1].sessions[0].groups[0].staffIds=[1];});
assert.equal(draft.changes.value.length,2);assert.equal(draft.history.value.length,1);assert.equal(JSON.stringify(base),initial);
draft.undo();assert.equal(draft.dirty.value,false);assert.equal(draft.changes.value.length,0);
draft.redo();assert.equal(draft.changes.value.length,2);
draft.undo();draft.edit(d=>d[0].sessions[0].groups[0].staffIds=[3]);assert.equal(draft.future.value.length,0);
assert.equal(draft.changes.value[0].before[0],1);assert.equal(draft.changes.value[0].after[0],3);
draft.undo();draft.options.value.timePins.push('1:11');assert.equal(draft.dirty.value,true);
assert.equal(JSON.stringify(base),initial);
console.log('PASS joint draft: atomic swap history, undo/redo, immutable saved source, replacement diff, divergent edit and pending constraints');
