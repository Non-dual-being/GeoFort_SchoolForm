<?php
declare(strict_types=1);
require dirname(__DIR__,2).'/vendor/autoload.php';
use GeoFort\Services\Dashboard\Roster\RosterJointStaffOptimizer;
$checks=0;
$assert=function(bool $ok,string $message) use (&$checks):void { $checks++;if(!$ok)throw new RuntimeException($message); };
$members=[];
foreach([[1,'paid',true,false],[2,'volunteer',true,false],[3,'paid',false,true],[4,'paid',true,true]] as [$id,$type,$guide,$cook]) $members[]=['id'=>$id,'name'=>'Person '.$id,'employmentType'=>$type,'isActive'=>true,'canGuide'=>$guide,'canCook'=>$cook,'preferences'=>[['moduleKey'=>'A','rank'=>1],['moduleKey'=>'B','rank'=>2]]];
$task=fn($id,$start,$end,$cook=false,$module='A')=>['staffId'=>$id,'startTime'=>$start,'endTime'=>$end,'cook'=>$cook,'moduleKey'=>$module,'availability'=>[]];
$o=new RosterJointStaffOptimizer();
$tasks=[$task(1,'10:00','10:45'),$task(2,'10:45','11:30'),$task(1,'12:00','12:45')];
$r=$o->optimize($tasks,$members);
$assert($r['before']['paidGapMinutes']===45,'Lunch must not count as a gap');
$assert($r['after']['paidGapMinutes']===0,'Paid gap not eliminated');
$paused=$tasks;
$paused[0]['breaks']=[['startTime'=>'10:45','endTime'=>'11:30']];
$pauseResult=$o->optimize($paused,$members);
$assert($pauseResult['before']['paidGapMinutes']===0,'School-specific break counted as a gap');
$assert($r===$o->optimize($tasks,$members),'Not deterministic');
$partial = $tasks;
$partial[0]['breaks'] = [['startTime'=>'10:55','endTime'=>'11:05']];
$partialResult = $o->optimize($partial, $members);
$assert($partialResult['before']['paidGapMinutes'] === 35, 'Partial morning break inside a day round must remove exactly ten minutes');
$tasks=[$task(3,'10:00','11:15',true),$task(4,'10:30','11:15',true),$task(4,'11:15','12:00',true)];
$r=$o->optimize($tasks,$members);
$assert($r['assignments'][2]===3,'Specialist cook should take over after overlap');
$assert($r['assignments'][0]!==$r['assignments'][1],'Overlapping cooks must differ');
$bundle=[$task(3,'10:00','10:45',true),$task(4,'10:00','10:45',true),$task(4,'11:00','11:45',true),$task(4,'12:00','12:45',true)];
$bundleResult=$o->optimize($bundle,$members);
$assert($bundleResult['assignments'][2]===3&&$bundleResult['assignments'][3]===3,'Afternoon cook sequence not moved together');
$assert(!$o->valid($tasks,[3,3,3]),'Cook overlap accepted');
$assert(!$o->valid([$task(1,'10:00','10:45')],[1],[['staffIds'=>[1],'startTime'=>'10:15','endTime'=>'11:00','moduleKey'=>'B']]),'External overlap accepted');
$t=$task(1,'10:00','10:45');$t['availability']=[1=>['11:00',null]];
$assert(!$o->valid([$t],[1]),'Availability ignored');
$t['availability']=[1=>['10:00','10:45']];
$assert($o->valid([$t],[1]),'Exact availability boundaries rejected');
$many=[];foreach(['A','B','C','D'] as $i=>$module)$many[]=$task(1,(10+$i).':00',(10+$i).':45',false,$module);
$assert($o->valid($many,[1,1,1,1]),'Fourth guide module rejected');
$many[]=$task(1,'14:00','14:45',false,'E');
$assert(!$o->valid($many,[1,1,1,1,1]),'Fifth guide module accepted');
$r=$o->optimize([$task(1,'10:00','10:45'),$task(2,'12:00','12:45')],$members);
$assert($r['before']['paidGapMinutes']===0,'Free morning/afternoon counted as gap');
$m=$members;$m[0]['isActive']=false;$r=$o->optimize([$task(2,'10:00','10:45')],$m);
$assert($r['assignments']===[2],'Unused/inactive staff introduced');
$balancedTasks = [$task(2,'10:00','10:45'), $task(1,'10:45','11:30'), $task(1,'11:30','12:15'), $task(1,'12:15','13:00')];
$balanced = $o->optimize($balancedTasks,$members);
$assert($balanced['after']['people']===1 && $balanced['after']['unfilledAssignments']===0, 'A complete day must be consolidated before balancing the remaining team');
$assert($balanced['after']['paidGapMinutes']===0, 'Fairness must not introduce a paid gap');
// Four-module KE may remain a concept exception, but coverage wins over savings.
$requiredKe=[...$task(0,'10:00','10:45',false,'B'),'schoolAllowed'=>true,'requiresGeoFortForFinal'=>true];
$coverage=$o->optimize([$task(1,'10:00','10:45'),$requiredKe],$members,[],[1,2]);
$assert($coverage['after']['people']===2 && $coverage['after']['keSchoolAssignments']===0,'Mandatory KE coverage sacrificed for headcount');
$concept=$o->optimize([$task(1,'10:00','10:45'),$requiredKe],$members,[],[1]);
$assert($concept['after']['keSchoolAssignments']===1 && $concept['after']['unfilledAssignments']===0,'Unavoidable KE exception must remain an explicit concept metric');
$optional=[...$requiredKe,'requiresGeoFortForFinal'=>false];
$five=$o->optimize([$task(1,'10:00','10:45'),$optional],$members,[],[1,2]);
$assert($five['after']['people']===1 && $five['after']['keSchoolAssignments']===0,'Five-module school guidance unexpectedly became mandatory');
$keMembers=$members;
foreach($keMembers as &$person)$person['preferences'][]=['moduleKey'=>'Klimaat-Experience','rank'=>3];unset($person);
$kePair=[...$task(1,'10:00','10:45',false,'Klimaat-Experience'),'planId'=>11,'sessionId'=>21,'groupCount'=>2,'groupIds'=>[31],'schoolAllowed'=>true,'requiresGeoFortForFinal'=>true];
$otherKe=[...$kePair,'staffId'=>2,'groupIds'=>[32]];
$shared=$o->optimize([$kePair,$otherKe],$keMembers);
$assert($shared['after']['people']===1 && $shared['after']['keSchoolAssignments']===0,'One qualified guide must be able to cover both groups in one KE session');
$assert(!$o->valid([$kePair,[...$otherKe,'planId'=>12]],[1,1]),'KE guide shared across two schools');
$assert(!$o->valid([$kePair,[...$otherKe,'sessionId'=>22]],[1,1]),'KE guide shared across two independent sessions');
$assert(!$o->valid([[...$kePair,'groupCount'=>3,'groupIds'=>[31,33]],$otherKe],[1,1]),'KE guide shared across three groups');
echo "PASS: {$checks} joint optimization domain checks\n";
